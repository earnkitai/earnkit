#!/usr/bin/env bash
# Writes the ABIs the app needs. Run after any contract change: bash script/export-abi.sh
set -euo pipefail
cd "$(dirname "$0")/.."
forge build --silent
out=../apps/frontend/lib/earnkit/escrow-abi.ts
{
  echo "// Generated by contracts/script/export-abi.sh. Do not edit."
  echo "export const campaignsAbi = $(forge inspect src/EarnKitCampaigns.sol:EarnKitCampaigns abi --json) as const;"
  echo "export const campaignAbi = $(forge inspect src/EarnKitCampaign.sol:EarnKitCampaign abi --json) as const;"
} > "$out"
npx prettier --write "$out" >/dev/null
echo "wrote $out"
