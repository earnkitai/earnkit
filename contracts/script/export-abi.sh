#!/usr/bin/env bash
# Writes the ABIs the app needs. Run after any contract change: bash script/export-abi.sh
set -euo pipefail
cd "$(dirname "$0")/.."
forge build --silent
out=../apps/frontend/lib/earnkit/escrow-abi.ts

campaigns_abi=$(forge inspect src/EarnKitCampaigns.sol:EarnKitCampaigns abi --json)
[ "${#campaigns_abi}" -gt 2 ] || { echo "empty ABI for EarnKitCampaigns" >&2; exit 1; }

campaign_abi=$(forge inspect src/EarnKitCampaign.sol:EarnKitCampaign abi --json)
[ "${#campaign_abi}" -gt 2 ] || { echo "empty ABI for EarnKitCampaign" >&2; exit 1; }

{
  echo "// Generated by contracts/script/export-abi.sh. Do not edit."
  echo "export const campaignsAbi = $campaigns_abi as const;"
  echo "export const campaignAbi = $campaign_abi as const;"
} > "$out"
npx prettier --write "$out" >/dev/null
echo "wrote $out"
